/**
 * Write `src/pi/official-prices.generated.ts`: the official model prices of the pi in Pier's
 * development dependencies, which hosts without pi use for usage costs (`usage.stats`, 1.70).
 * Run it (`bun run update-prices`) after upgrading the pi development dependency;
 * `test/model-prices.test.ts` fails while the file is out of date.
 */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { getBuiltinModels, getBuiltinProviders } from "@earendil-works/pi-ai/providers/all";
import { officialPriceSnapshot, type PricedCatalogModel } from "../src/pi/model-prices.ts";

const here = dirname(fileURLToPath(import.meta.url));
const target = join(here, "..", "src", "pi", "official-prices.generated.ts");
// pi-ai exports only its modules; its package.json is next to `dist/`.
const piAiEntry = fileURLToPath(import.meta.resolve("@earendil-works/pi-ai"));
const piAi = JSON.parse(readFileSync(join(dirname(piAiEntry), "..", "package.json"), "utf8")) as { version: string };

const models: PricedCatalogModel[] = getBuiltinProviders().flatMap((provider) =>
	(getBuiltinModels(provider) as readonly { provider: string; id: string; cost?: unknown }[]).map(
		({ provider: owner, id, cost }) => ({ provider: owner, id, cost }),
	),
);
const snapshot = officialPriceSnapshot(models);

writeFileSync(
	target,
	`// Generated by \`bun run update-prices\` from the model catalog of @earendil-works/pi-ai ${piAi.version}. Do not edit.
import type { PricedCatalogModel } from "./model-prices.ts";

/** Official prices (US dollars per million tokens) of model vendors' own catalog entries. */
export const OFFICIAL_PRICES: readonly PricedCatalogModel[] = ${JSON.stringify(snapshot)};
`,
);
execFileSync(join(here, "..", "..", "..", "node_modules", ".bin", "biome"), ["format", "--write", target], {
	stdio: "inherit",
});
console.log(`${snapshot.length} prices from pi-ai ${piAi.version} → ${target}`);
